#!/usr/bin/env python3
"""Generate a random exploration route (for `capture` snapshots): python3 make_explore.py SEED FRAMES > route.txt
Starts like smoke.txt (title -> new game -> intro), then walks around pressing every button: A (talk/confirm),
B (attack), R (ki blast), L, START/SELECT menus (left again with B)."""
import random, sys
seed, total = int(sys.argv[1]), int(sys.argv[2])
r = random.Random(seed)
out = ['# Random exploration after the intro (seed %d, ~%d frames); generated by tools/harness/make_explore.py' % (seed, total)]
intro = [l for l in open(__file__.replace('make_explore.py', 'smoke.txt')).read().split('\n')
         if l and not l.startswith('#') and not l.startswith('shot')]
out += intro
f = 0
dirs = ['UP', 'DOWN', 'LEFT', 'RIGHT', 'UP,LEFT', 'UP,RIGHT', 'DOWN,LEFT', 'DOWN,RIGHT']
while f < total:
    x = r.random()
    if x < 0.45:
        n = r.randint(10, 90); out += ['keys %s' % r.choice(dirs), 'run %d' % n]; f += n
    elif x < 0.65:
        n = r.randint(5, 40); out += ['keys %s,B' % r.choice(dirs), 'run %d' % n]; f += n
    elif x < 0.75:
        out += ['keys', 'tap R %d' % r.randint(10, 40)]; f += 40
    elif x < 0.88:
        out += ['keys', 'tap A %d' % r.randint(20, 80)]; f += 80
    elif x < 0.92:
        out += ['keys', 'tap L 30']; f += 34
    elif x < 0.96:
        out += ['keys', 'tap START 40']
        for _ in range(r.randint(0, 4)): out.append('tap %s 20' % r.choice(['RIGHT', 'LEFT', 'DOWN', 'UP', 'A', 'R', 'L']))
        out += ['tap B 30', 'tap B 30', 'tap START 40']; f += 200
    else:
        out += ['keys', 'tap SELECT 40', 'tap B 30', 'tap SELECT 30']; f += 110
    if r.random() < 0.02: out.append('shot x%05d' % f)
out.append('keys')
print('\n'.join(out))
