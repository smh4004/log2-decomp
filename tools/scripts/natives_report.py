#!/usr/bin/env python3
"""Write docs/script_natives.md: every script native with its address, current name, a guess at how many arguments
it pops, and the first lines of its reference C (ref/). Use it to name natives in config/script_natives.txt."""
import os, re, sys, glob, struct
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
os.chdir(os.path.join(HERE, '..', '..'))
import l2script as B
sys.path.insert(0, os.path.join(HERE, '..', 'assets'))
from const import NATIVES
d = open('baserom.gba', 'rb').read()
names = B.load_names()
src = ''.join(open(f).read() for f in sorted(glob.glob('ref/*.c')))
out = ['# Script natives (generated by tools/scripts/natives_report.py)', '',
       'Natives are the game functions scripts call (`call NAME(args)`). Arguments are popped from the stack, the last',
       'pushed first. "pops" counts stack pops in the reference C (a guess: it can miss pops in loops or callees).',
       'Natives 0x00-0x10 are also vars (`set`, `inc`, ...: setter table at 0x083B5F70). Name one by adding',
       '`0xNN name` to config/script_natives.txt.', '']
for n in range(NATIVES[1]):
    a = struct.unpack_from('<I', d, NATIVES[0] + 4 * n)[0] & ~1
    if not a: continue
    m = re.search(r'/\* (\w+) @ 0x%08X \*/\n(.*?)(?=\n/\* \w+ @ 0x)' % a, src, re.S)
    body = m.group(2).strip() if m else ''
    pops = len(re.findall(r'\*param_1 = \w+ \+ -1;', body)) + 2 * len(re.findall(r'\*param_1 = \w+ \+ -2;', body))
    lines = [l for l in body.split('\n') if l.strip()][:12]
    out.append('## 0x%02X %s  (`%s`, 0x%08X, pops ~%d)' % (n, names.get(n, ''), m.group(1) if m else '?', a, pops))
    out += ['```c'] + lines + ['```', '']
open('docs/script_natives.md', 'w').write('\n'.join(out) + '\n')
print('wrote docs/script_natives.md (%d natives, %d named)' % (NATIVES[1], sum(1 for k in names if k < NATIVES[1])))
