#!/usr/bin/env python3
"""Classify every byte of baserom.gba and write config/regions.yaml.

Classes:
  header      cartridge header
  code_thumb  / code_arm   traced instructions
  pool        literal-pool words referenced by code
  switch      ADS switch offset tables
  vtable      base-relative C++ vtables, ctor vector (relative offsets)
  data        other data that sits inside the code area (strings, FP constants, tables)
  wfz         compressed data: WFZ container (header + bitstream) or GBA BIOS Huffman/LZ77 stream
  rodata      uncompressed tables / raw assets in .rodata
  iwram_code / iwram_data   RW image copied to IWRAM by crt0
  padding     0xFF fill after the RW image / zero alignment
  unknown     not classified (dead code candidates inside the code area)
Merges adjacent bytes of equal class into ranges.
"""
import os, sys, json, pickle, struct, collections
sys.path.insert(0, os.path.dirname(__file__))
from analyze import ROM, CTOR_LO, CTOR_HI, VT_LO, VT_HI
from game import TEXT_END, TEXT_START

os.chdir(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
d = open('baserom.gba', 'rb').read()
db = pickle.load(open('.analysis/analysis.pickle', 'rb'))
blocks = json.load(open('.analysis/wfz_blocks.json'))
if os.path.exists('.analysis/lz_blocks.json'):           # GBA BIOS streams (bios_blocks games): also compressed
    from game import BIOS_BLOCKS
    if BIOS_BLOCKS: blocks += json.load(open('.analysis/lz_blocks.json'))
IW_OFF, IW_VMA, IW_SIZE = db['iwram']
N = len(d)
C = ['unknown', 'header', 'code_thumb', 'code_arm', 'pool', 'switch', 'vtable', 'data', 'wfz', 'rodata',
     'iwram_code', 'iwram_data', 'padding']
K = {n: i for i, n in enumerate(C)}
cls = bytearray(N)

def off(a): return a - ROM if a >= ROM else IW_OFF + a - IW_VMA

cls[0:0xC0] = bytes([K['header']]) * 0xC0
for a, (m, s) in db['insn'].items():
    k = 'code_thumb' if m == 't' else 'code_arm'
    if a < ROM: k = 'iwram_code'
    cls[off(a):off(a) + s] = bytes([K[k]]) * s
for a in db['pool']:
    cls[off(a):off(a) + 4] = bytes([K['pool' if a >= ROM else 'iwram_code']]) * 4
for t, (n, base, tg, esz) in db['jt'].items():
    cls[off(t):off(t) + n * esz] = bytes([K['switch']]) * (n * esz)
for e in db['vt_ents']: cls[e:e + 4] = bytes([K['vtable']]) * 4
cls[CTOR_LO:CTOR_HI] = bytes([K['vtable']]) * (CTOR_HI - CTOR_LO)
# remaining bytes in the code area
for o in range(0xC0, TEXT_END):
    if cls[o] == 0:
        cls[o] = K['data'] if (VT_LO <= o < VT_HI) else 0
# strings / constants inside code area: printable runs or zero alignment
o = 0xC0
while o < TEXT_END:
    if cls[o] == 0:
        e = o
        while e < TEXT_END and cls[e] == 0: e += 1
        chunk = d[o:e]
        if all(x == 0 for x in chunk) and e - o < 4: cls[o:e] = bytes([K['padding']]) * (e - o)
        elif sum(32 <= x < 127 or x == 0 for x in chunk) >= 0.8 * len(chunk) and e - o >= 4:
            cls[o:e] = bytes([K['data']]) * (e - o)
        o = e
    else:
        o += 1
# rodata
for o2, s, e, t in blocks: cls[o2:e] = bytes([K['wfz']]) * (e - o2)
for o in range(TEXT_END, IW_OFF):
    if cls[o] == 0: cls[o] = K['rodata']
for o in range(IW_OFF, IW_OFF + IW_SIZE):
    if cls[o] == 0: cls[o] = K['iwram_data']
cls[IW_OFF + IW_SIZE:] = bytes([K['padding']]) * (N - IW_OFF - IW_SIZE)

# merge
ranges = []
i = 0
while i < N:
    j = i
    while j < N and cls[j] == cls[i]: j += 1
    ranges.append((i, j, C[cls[i]]))
    i = j
tot = collections.Counter()
for a, b, k in ranges: tot[k] += b - a
os.makedirs('config', exist_ok=True)
with open('config/regions.yaml', 'w') as f:
    f.write('# Byte classification of baserom.gba (generated by tools/bfdis/regions.py).\n')
    f.write('# start/end are ROM file offsets (end exclusive). 100% coverage.\n')
    f.write('summary:\n')
    for k in C:
        f.write('  %-11s %9d  # %5.2f%%\n' % (k + ':', tot[k], 100.0 * tot[k] / N))
    f.write('sections:\n')
    for s in [('header', 0, 0xC0), ('crt0', 0xC0, TEXT_START), ('text', TEXT_START, CTOR_LO), ('ctorvec', CTOR_LO, CTOR_HI),
              ('veneers', CTOR_HI, VT_LO), ('vtables', VT_LO, VT_HI), ('text2', VT_HI, TEXT_END),
              ('rodata', TEXT_END, IW_OFF), ('rw_image_iwram', IW_OFF, IW_OFF + IW_SIZE), ('padding', IW_OFF + IW_SIZE, N)]:
        f.write('  - {name: %s, start: 0x%06X, end: 0x%06X}\n' % s)
    f.write('regions:\n')
    for a, b, k in ranges:
        f.write('  - [0x%06X, 0x%06X, %s]\n' % (a, b, k))
print(len(ranges), 'ranges')
for k in C: print('%-11s %9d %6.2f%%' % (k, tot[k], 100.0 * tot[k] / N))
