#!/usr/bin/env python3
"""Generate the assembly/data source tree from baserom.gba.

usage: gen.py baserom.gba [--reanalyze]

Writes (all derived from the user's ROM; regenerate any time):
  .analysis/analysis.pickle, .analysis/wfz_blocks.json   caches (not committed)
  asm/code_*.s, asm/crt0.s       code area 0x080000C0..0x08054FBB
  asm/iwram.s                    RW image (linked at 0x03000000, loaded after .rodata)
  data/rodata_*.s                .rodata: labels + symbolic pointers, incbin between them
  config/code_files.txt, config/data_files.txt   link order
  config/ptr_ambiguous.txt       pointer-like words left as numbers (see docs/shifting.md)
"""
import sys, os, pickle, struct, collections, hashlib, json, re, glob, subprocess
sys.path.insert(0, os.path.dirname(__file__))
from analyze import full_analysis, ctor_targets, CTOR_LO, ROM
from emit import Emitter
from ptrs import classify

from game import SHA1 as BASEROM_SHA1, TEXT_START, TEXT_END, IWRAM, IMAGE_END, CTOR_LO, CTOR_HI, VT_LO, VT_HI, NAME
RO_LO, RO_HI = TEXT_END, IWRAM[0]
SPLIT_TARGET = 0x2000
DATA_SPLIT = 0x80000


def load_rom(path):
    d = open(path, 'rb').read()
    if hashlib.sha1(d).hexdigest() != BASEROM_SHA1:
        sys.exit('baserom.gba: wrong SHA-1 (need %s)' % BASEROM_SHA1)
    return d


def analyze(d, cache):
    if os.path.exists(cache) and '--reanalyze' not in sys.argv:
        return pickle.load(open(cache, 'rb'))
    A = full_analysis(d, TEXT_END, IWRAM)
    db = dict(insn=A.insn, pool={k: sorted(v) for k, v in A.pool.items()}, jt=A.jt,
              funcs=dict(A.funcs), labels=sorted(A.labels), vt_bases=A.vt_bases,
              vt_ents=A.vt_ents, iwram=IWRAM, calls={k: sorted(v) for k, v in A.calls.items()})
    db['ctor'] = {e: (t, m) for e, t, m in ctor_targets(d)}
    relpool = {}   # MI thunk literal: target = (add ip,pc,ip) + 8 + word
    for a, (m, s) in A.insn.items():
        if m == 'a' and A.u32(a) == 0xE08FC00C and A.off(a - 8) is not None and A.u32(a - 8) == 0xE59FC008:
            la = a + 8; tgt = la + A.s32(la)
            relpool[la] = (la, tgt & ~1, 't' if tgt & 1 else 'a')
            db['labels'].append(la)
    db['relpool'] = relpool
    os.makedirs(os.path.dirname(cache), exist_ok=True)
    pickle.dump(db, open(cache, 'wb'))
    return db


def wfz_blocks(path):
    if not os.path.exists(path):
        print('scanning for WFZ containers ...')
        subprocess.check_call([sys.executable, 'tools/wfz/scan_wfz.py', 'baserom.gba', path, '%X' % RO_LO, '%X' % RO_HI])
    blocks = json.load(open(path))
    # GBA BIOS streams (Huffman / LZ77 / RLE, tools/bfdis/lz.py) are compressed bytes too
    lzp = os.path.join(os.path.dirname(path), 'lz_blocks.json')
    from game import BIOS_BLOCKS
    if not BIOS_BLOCKS: return blocks
    if not os.path.exists(lzp):
        subprocess.check_call([sys.executable, 'tools/bfdis/lz.py', 'baserom.gba', lzp, '%X' % RO_LO, '%X' % RO_HI])
    taken = sorted((o, e) for o, sz, e, t in blocks)
    import bisect as _b
    for blk in json.load(open(lzp)):
        i = _b.bisect_right(taken, (blk[0], 1 << 40)) - 1
        if i >= 0 and taken[i][0] <= blk[0] < taken[i][1]: continue
        blocks.append(blk)
    return blocks


def load_kv(path):
    sym = {}
    if os.path.exists(path):
        for line in open(path):
            line = line.split('#')[0].strip()
            if not line: continue
            a, n = line.split()[:2]
            sym[int(a, 16)] = n
    return sym


def load_raw(path):
    s = set()
    if os.path.exists(path):
        for line in open(path):
            line = line.split('#')[0].strip()
            if line: s.add(int(line.split()[0], 16))
    return s


def entry_branch(d):
    """`b _start` when the ROM's first word is that branch (to 0x080000C0), else the raw word (prototypes)."""
    w = struct.unpack_from('<I', d, 0)[0]
    return 'b _start' if w == 0xEA00002E else '.4byte 0x%08X   @ entry branch (not to _start)' % w


def write_header(d):
    """asm/header.s from the ROM's own header fields (the Nintendo logo stays an incbin)."""
    t = d[0xA0:0xAC]
    open('asm/header.s', 'w').write('''@ GBA cartridge header (0x08000000-0x080000BF). Generated by tools/bfdis/gen.py.
@ The Nintendo logo is pulled from baserom.gba at build time; nothing copyrighted lives here.
	.syntax unified
	.arm
	.text
	.global RomHeader
RomHeader:
	%s
RomHeaderNintendoLogo:
	.incbin "baserom.gba", 0x4, 0x9C
RomHeaderGameTitle:
	.byte %s
RomHeaderGameCode:
	.byte %s
RomHeaderMakerCode:
	.byte %s
RomHeaderMagic:
	.byte 0x%02X
RomHeaderMainUnitCode:
	.byte %d
RomHeaderDeviceType:
	.byte %d
RomHeaderReserved1:
	.byte %s
RomHeaderSoftwareVersion:
	.byte %d
RomHeaderChecksum:
	.byte 0x%02X
RomHeaderReserved2:
	.byte %d, %d
''' % (entry_branch(d), ', '.join('0x%02X' % c for c in t), ', '.join('0x%02X' % c for c in d[0xAC:0xB0]), ', '.join('0x%02X' % c for c in d[0xB0:0xB2]), d[0xB2], d[0xB3], d[0xB4],
       ', '.join(str(c) for c in d[0xB5:0xBC]), d[0xBC], d[0xBD], d[0xBE], d[0xBF]))


def main():
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    os.chdir(root)
    d = load_rom('baserom.gba')
    write_header(d)
    db = analyze(d, '.analysis/analysis.pickle')
    blocks = wfz_blocks('.analysis/wfz_blocks.json')
    sym = load_kv('config/symbols.txt')
    raw = load_raw('config/raw_insns.txt')
    insn = db['insn']

    # ---------------------------------------------------------------- pointers in .rodata
    acc, amb = classify(d, db, blocks, TEXT_END, RO_LO, RO_HI, IMAGE_END)
    for o, (w, k) in acc.items():                    # data pointers to code = function entry points
        if k == 'func':
            t = w & ~1
            if t in insn and t not in db['funcs']: db['funcs'][t] = insn[t][0]
    with open('config/ptr_ambiguous.txt', 'w') as f:
        f.write('# Pointer-like words in .rodata NOT converted to symbols (generated by tools/bfdis/gen.py).\n')
        f.write('# offset    value       reason\n')
        for o in sorted(amb):
            f.write('%06X  %08X  %s\n' % (o, amb[o][0], amb[o][1]))

    E = Emitter(d, db, sym, raw)
    E.even = set()
    ro_labels = set(a - ROM for a in sym if ROM + RO_LO <= a < ROM + RO_HI)

    def target_expr(w, ref):
        """Symbolic expression for pointer value w, or None to keep the number."""
        if ROM <= w < ROM + TEXT_END:
            if w & 1 and (w - 1) in insn and insn[w - 1][0] == 't':
                return '%s + 1' % ref(w - 1)
            t = w
            if (t - 2) in insn and insn[t - 2][1] == 4: return None      # middle of a BL pair
            if t in db['funcs'] and db['funcs'][t] == 't':             # even ptr to Thumb code: ld would set bit 0 on
                E.even.add(t); return '%s_even' % ref(t)                  # the function symbol, so use a plain alias label
            if t < ROM + 0xC0: return None                                # header
            return ref(t)
        if ROM + RO_LO <= w < ROM + RO_HI:
            ro_labels.add(w - ROM)
            return 'gUnknown_%08X' % w if w not in sym else sym[w]
        if ROM + RO_HI <= w < ROM + IMAGE_END:
            return '__iwram_lma + 0x%X' % (w - ROM - RO_HI) if w != ROM + RO_HI else '__iwram_lma'
        if IWRAM[1] <= w < IWRAM[1] + IWRAM[2]:
            if w & 1 and (w - 1) in insn and insn[w - 1][0] == 't': return '%s + 1' % ref(w - 1)
            # inside the RW image: only instruction starts and data words are addresses (0x030000FA in the middle of
            # an ARM instruction is just a number)
            if any((w - k) in insn and k < insn[w - k][1] for k in range(1, 4)): return None
            return ref(w)
        return None

    E.ptr_sym = lambda w: target_expr(w, E.ref)

    # ---------------------------------------------------------------- split points for code
    lo, hi = ROM + 0xC0, ROM + TEXT_END
    spans = []
    for la, refs in db['pool'].items():
        for r in refs: spans.append((r, la))
    for t, (n, base, tg, esz) in db['jt'].items():
        for x in tg: spans.append((base - 4, x))
        spans.append((base - 4, t + n * esz))
    for a, (m, s) in insn.items():
        if m == 't' and s == 2:
            h = E.u16(a)
            if (h >> 12) == 0xD and ((h >> 8) & 0xF) < 0xE:
                off = h & 0xFF; off = off - 0x100 if off & 0x80 else off; spans.append((a, a + 4 + off * 2))
            elif (h >> 11) == 0x1C:
                off = h & 0x7FF; off = off - 0x800 if off & 0x400 else off; spans.append((a, a + 4 + off * 2))
            elif (h >> 11) == 0x14:
                spans.append((a, ((a + 4) & ~3) + (h & 0xFF) * 4))
        elif m == 'a':
            w = E.u32(a)
            if (w & 0x0F000000) == 0x0A000000:
                off = w & 0xFFFFFF; off = off - 0x1000000 if off & 0x800000 else off
                if abs(off * 4) > 0x1000: db['funcs'].setdefault(a + 8 + off * 4, 'a')
                spans.append((a, a + 8 + off * 4))
    ev = collections.Counter()
    fstarts = set(db['funcs'])
    for x, y in spans:
        if y in fstarts and y in insn: continue          # tail call: linker resolves
        if x > y: x, y = y, x
        ev[x + 1] += 1; ev[y + 1] -= 1
    fset = set(f for f in db['funcs'] if lo < f < hi and f in insn)
    cuts = []; depth = 0; last = lo
    for p in sorted(set(ev) | fset):
        depth += ev.get(p, 0)
        if p in fset and depth == 0 and p % 4 == 0 and p - last >= SPLIT_TARGET:
            cuts.append(p); last = p
    bounds = sorted(set([ROM + 0xC0, ROM + TEXT_START] + [c for c in cuts if c > ROM + TEXT_START] + [hi]))

    # ---------------------------------------------------------------- replaceable functions (for `make decomp`)
    # A Thumb function [start, next function start) can be dropped from the assembly when nothing outside
    # it refers to a label strictly inside it.
    allstarts = sorted(set(f for f in db['funcs'] if f in insn and lo <= f < hi) | set(bounds))
    import bisect as _bs
    inner_refs = collections.defaultdict(set)      # target -> set(sources)
    for x, y in spans: inner_refs[y].add(x)
    for la in db['pool']:
        if la >= ROM:
            v = E.u32(la)
            if lo <= (v & ~1) < hi: inner_refs[v & ~1].add(la)
    for o, (w, k) in acc.items():
        if lo <= (w & ~1) < hi: inner_refs[w & ~1].add(ROM + o)
    for e2, (b2, t2, m2) in db['vt_ents'].items(): inner_refs[t2].add(ROM + e2)
    # targets of B/Bcc from other functions (tail calls): Thumb B only reaches +-2 KB, so these stay in place
    tailcalled = set()
    for a, (m, sz) in insn.items():
        if m == 't' and sz == 2 and a >= ROM:
            h = E.u16(a)
            if (h >> 11) == 0x1C:
                off = h & 0x7FF; off = off - 0x800 if off & 0x400 else off; tailcalled.add(a + 4 + off * 2)
            elif (h >> 12) == 0xD and ((h >> 8) & 0xF) < 0xE:
                off = h & 0xFF; off = off - 0x100 if off & 0x80 else off; tailcalled.add(a + 4 + off * 2)
    tailcalled = {t for t in tailcalled if t in db['funcs']}
    wrap = {}
    for i, f in enumerate(allstarts[:-1]):
        if db['funcs'].get(f) != 't' or not (ROM + TEXT_START <= f < ROM + CTOR_LO or ROM + VT_HI <= f < hi): continue
        e = allstarts[i + 1]
        # the decomp build overwrites the function with a 16-18 byte long jump (see Emitter.decomp_else).
        # Tail calls (b/bcc into it) are fine: they land on the jump.
        ok = e - f >= (16 if f % 4 == 0 else 18)

        for t in inner_refs:
            if f < t < e and any(not (f <= src < e) for src in inner_refs[t]): ok = False; break
        if ok: wrap[f] = e
    E.wrap = wrap
    open('config/replaceable.txt', 'w').write(''.join('%08X %08X %s\n' % (f, e, E.name(f)) for f, e in sorted(wrap.items())))

    # ---------------------------------------------------------------- emit code (two passes for labels)
    E.needed_hint = set()
    for p in range(2):
        E.needed = set()
        files = []
        for i in range(len(bounds) - 1):
            a, b = bounds[i], bounds[i + 1]
            name = 'crt0' if a == ROM + 0xC0 else 'code_%08X' % a
            files.append(('asm/%s.s' % name, a, b, E.emit_range(a, b, [])))
        files.append(('asm/iwram.s', IWRAM[1], IWRAM[1] + IWRAM[2], E.emit_range(IWRAM[1], IWRAM[1] + IWRAM[2], [])))
        # rodata pointers reference code labels too: register them before the second pass
        for o, (w, k) in acc.items(): target_expr(w, E.ref)
        E.needed_hint = set(E.needed)

    # ---------------------------------------------------------------- emit .rodata
    events = {}
    for o, (w, k) in acc.items(): events[o] = w
    keys = sorted(set(events) | ro_labels)
    data_files = []
    pos = chunk_start = RO_LO
    lines = []
    def incbin(a, b):
        if b > a: lines.append('\t.incbin "baserom.gba", 0x%X, 0x%X' % (a, b - a))
    def lname(k):
        return sym.get(ROM + k, 'gUnknown_%08X' % (ROM + k))
    for k in keys:
        if k in ro_labels and k - chunk_start >= DATA_SPLIT and k >= pos:
            incbin(pos, k); pos = k
            data_files.append(('data/rodata_%08X.s' % (ROM + chunk_start), ROM + chunk_start, ROM + k, lines))
            lines = []; chunk_start = k
        if k < pos:                                   # label inside an emitted word
            if k in ro_labels: lines.append('\t.set %s, . - %d' % (lname(k), pos - k))
            continue
        incbin(pos, k); pos = k
        if k in ro_labels: lines.append('%s:' % lname(k))
        if k in events:
            w = events[k]
            x = target_expr(w, E.ref)
            lines.append('\t.4byte %s' % x if x else '\t.4byte 0x%08X' % w)
            pos = k + 4
    incbin(pos, RO_HI)
    data_files.append(('data/rodata_%08X.s' % (ROM + chunk_start), ROM + chunk_start, ROM + RO_HI, lines))

    # ---------------------------------------------------------------- write files, add .global for cross-file refs
    for old in glob.glob('asm/code_*.s') + glob.glob('data/rodata*.s'): os.remove(old)
    allfiles = files + data_files
    defs = {}
    for name, a, b, lines in allfiles:
        for l in lines:
            m = re.match(r'^([A-Za-z_.$][\w.$]*):', l) or re.match(r'^\t\.set ([A-Za-z_][\w]*),', l)
            if m: defs[m.group(1)] = name
    xref = collections.defaultdict(set)
    tokre = re.compile(r'\b([A-Za-z_][\w]*)\b')
    for name, a, b, lines in allfiles:
        for l in lines:
            if l.startswith('\t.incbin'): continue
            body = l.split('@')[0]
            for u in tokre.findall(body):
                if u in defs and defs[u] != name: xref[defs[u]].add(u)
    for name, a, b, lines in allfiles:
        os.makedirs(os.path.dirname(name), exist_ok=True)
        isdata = name.startswith('data/')
        hdr = ['@ Generated by tools/bfdis/gen.py from baserom.gba -- 0x%08X-0x%08X' % (a, b)]
        if isdata:
            hdr += ['\t.section .rodata']
        else:
            hdr += ['\t.include "asm/macros.inc"', '\t.syntax unified', '\t.text']
        # every label is global so C code (make decomp) and tools can link against any of them
        mine = sorted(k for k, v in defs.items() if v == name)
        hdr += ['\t.global %s' % g for g in mine]
        with open(name, 'w') as f:
            f.write('\n'.join(hdr + [''] + lines) + '\n')
    open('config/code_files.txt', 'w').write(''.join(os.path.basename(n)[:-2] + '\n' for n, a, b, l in files if 'iwram' not in n))
    open('config/data_files.txt', 'w').write(''.join(os.path.basename(n)[:-2] + '\n' for n, a, b, l in data_files))
    subprocess.check_call([sys.executable, 'tools/bfdis/pinned.py'])
    print('code files %d, data files %d, rodata pointers %d (ambiguous %d), rodata labels %d'
          % (len(files), len(data_files), len(acc), len(amb), len(ro_labels)))


if __name__ == '__main__':
    main()
